"""Generate readable code from a plan.

Output, per pipeline:

    src/<name>/transforms.py   one PySpark function per fused dataflow region
    src/<name>/workflow.py     the LangGraph definition (agents, routers, approvals)
    src/<name>/main.py         job entry point
    src/strand_runtime/        the small runtime package, copied in
    databricks.yml             Databricks Asset Bundle
    resources/<name>.job.yml   the Lakeflow job
"""
from __future__ import annotations

import json
import re
import textwrap
from pathlib import Path

import yaml

from .plan import Plan, Unit
from .spec import Node, Pipeline

HEADER = '"""Generated by strand from pipeline \'{name}\'. Edit the pipeline and recompile; do not edit this file."""\n'
RUNTIME_DIR = Path(__file__).resolve().parent.parent / "strand_runtime"


def r(value) -> str:
    """Python literal, preferring double quotes and triple quotes for multi-line text."""
    if isinstance(value, str):
        if "\n" in value and '"""' not in value and not value.endswith('"') and "\\" not in value:
            return '"""' + value + '"""'
        return json.dumps(value, ensure_ascii=False)
    return repr(value)


def sql_literal(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def prompt_to_sql(template: str) -> str:
    """'Classify: {body}' -> concat('Classify: ', CAST(`body` AS STRING))"""
    parts: list[str] = []
    for i, piece in enumerate(re.split(r"\{(\w+)\}", template)):
        if i % 2:
            parts.append(f"CAST(`{piece}` AS STRING)")
        elif piece:
            parts.append(sql_literal(piece))
    return parts[0] if len(parts) == 1 else "concat(" + ", ".join(parts) + ")"


# ----------------------------------------------------------------------------- dataflow


def node_expr(p: Pipeline, n: Node, limit: int | None = None) -> list[str]:
    """Lines that bind the DataFrame of a dataflow node to a variable named after the node."""
    ins = p.data_inputs(n.id)
    first = ins[0].source if ins else None
    g = n.get
    if n.type == "source":
        if g("table"):
            expr = f"spark.read.table({r(g('table'))})"
        else:
            expr = f"spark.read.format({r(g('format'))}).load({r(g('path'))})"
        if limit:
            expr += f".limit({limit})"
        return [f"{n.id} = {expr}"]
    if n.type == "filter":
        return [f"{n.id} = {first}.filter({r(g('condition'))})"]
    if n.type == "sql":
        names = sorted({e.source for e in ins})
        args = "".join(f", {name}={name}" for name in names)
        return [f"{n.id} = spark.sql({r(g('query'))}{args})"]
    if n.type == "python":
        body = textwrap.indent(textwrap.dedent(g("code")).strip("\n"), "    ")
        return [f"def _{n.id}(df, spark):", *body.splitlines(), f"{n.id} = _{n.id}({first}, spark)"]
    if n.type == "join":
        left = next(e.source for e in ins if e.port == "left")
        right = next(e.source for e in ins if e.port == "right")
        return [f"{n.id} = {left}.join({right}, on={g('on')!r}, how={r(g('how'))})"]
    if n.type == "llm_map":
        call = f"ai_query({sql_literal(g('endpoint'))}, {prompt_to_sql(g('prompt'))}) AS `{g('output_column')}`"
        return [
            "# One batch call per row on Spark. Not an agent loop: no tools, no memory.",
            f"{n.id} = {first}.selectExpr(\"*\", {r(call)})",
        ]
    if n.type == "sink":
        return []
    raise ValueError(n.type)


def gen_region(p: Pipeline, u: Unit) -> str:
    chain = " -> ".join(u.nodes)
    out = [
        f"def {u.id}(ctx: RunContext, datasets: dict[str, dict]) -> dict[str, dict]:",
        f'    """{chain}',
        "",
        "    One lazy Spark plan. Tables are written only at the marked points.",
        '    """',
        "    spark = ctx.spark",
        "    out: dict[str, dict] = {}",
    ]
    for ref in u.reads:
        out += ["", f"    # {ref} · written by an earlier step, read back by reference", f"    {ref} = ctx.read(datasets[{r(ref)}])"]
    for nid in u.nodes:
        n = p.node(nid)
        out += ["", f"    # {nid} · {n.node_type.label}" + (f" · {n.label}" if n.label else "")]
        out += ["    " + line for line in node_expr(p, n)]
        if n.type == "sink":
            src = p.data_inputs(nid)[0].source
            extra = f", merge_keys={n.get('merge_keys')!r}" if n.get("mode") == "merge" else ""
            out.append(f"    out[{r(nid)}] = ctx.write_sink({r(nid)}, {src}, table={r(n.get('table'))}, mode={r(n.get('mode'))}{extra})")
        elif nid in u.materialize:
            out.append(f"    # materialised: {u.materialize[nid]}")
            out.append(f"    out[{r(nid)}] = ctx.materialize({r(nid)}, {nid})")
            if any(e.source == nid and e.target in u.nodes for e in p.edges):
                out.append(f"    {nid} = ctx.read(out[{r(nid)}])  # reuse the written table instead of recomputing")
    out += ["", "    return out"]
    return "\n".join(out)


def gen_transforms(p: Pipeline, plan: Plan) -> str:
    regions = [u for u in plan.units if u.kind == "region"]
    parts = [
        HEADER.format(name=p.name),
        "from __future__ import annotations\n",
        "from typing import TYPE_CHECKING\n",
        "if TYPE_CHECKING:\n    from strand_runtime import RunContext\n",
    ]
    parts += ["\n" + gen_region(p, u) + "\n" for u in regions]
    return "\n".join(parts)


# ----------------------------------------------------------------------------- control flow


def gen_control(p: Pipeline, plan: Plan, u: Unit) -> str:
    n = p.node(u.id)
    g = n.get
    head = f"def {n.id}(state: rt.State) -> dict:"
    doc = f'    """{n.node_type.label}' + (f": {n.label}" if n.label else "") + '"""'
    if n.type == "agent":
        kwargs = {
            "endpoint": g("endpoint"),
            "system_prompt": g("system_prompt") or "",
            "instructions": g("instructions"),
            "reads": u.reads,
            "uc_functions": g("uc_functions") or [],
            "vector_indexes": g("vector_indexes") or [],
            "choices": g("choices") or [],
            "include_sample": bool(g("include_sample")),
            "max_steps": int(g("max_steps") or 8),
        }
        args = "\n".join(f"        {k}={r(v)}," for k, v in kwargs.items() if v not in ([], "", False))
        return f"{head}\n{doc}\n    return rt.run_agent(\n        state,\n        {r(n.id)},\n{args}\n    )"
    if n.type == "router":
        return "\n".join([
            head, doc,
            '    datasets, outputs = state.get("datasets", {}), state.get("outputs", {})',
            f"    value = {g('expr').strip()}",
            f"    return rt.router_result(state, {r(n.id)}, value, max_iterations={int(g('max_iterations') or 3)})",
        ])
    if n.type == "approval":
        reads = "{" + ", ".join(f'{r(x)}: state["datasets"].get({r(x)})' for x in u.reads) + "}"
        return "\n".join([
            head, doc,
            "    # The run stops here and the job ends. Approving starts a new job run that",
            "    # re-enters this function, where interrupt() returns the decision.",
            f"    decision = interrupt({{\"node\": {r(n.id)}, \"message\": {r(g('message'))}, \"datasets\": {reads}}})",
            f"    return rt.approval_result({r(n.id)}, decision)",
        ])
    raise ValueError(n.type)


def gen_workflow(p: Pipeline, plan: Plan) -> str:
    out = [
        HEADER.format(name=p.name),
        "from __future__ import annotations\n",
        "from langgraph.graph import END, START, StateGraph",
        "from langgraph.types import interrupt  # noqa: F401\n",
        "import strand_runtime as rt\n",
        "from . import transforms\n",
        f"PIPELINE = {r(p.name)}",
        f"SETTINGS = {p.settings.model_dump()!r}\n",
        "\n# ---- steps",
    ]
    for u in plan.units:
        if u.kind == "region":
            out.append(
                f"\n\ndef {u.id}(state: rt.State) -> dict:\n"
                f'    """Spark: {" -> ".join(u.nodes)}"""\n'
                f"    return rt.run_region(state, {r(u.id)}, transforms.{u.id})"
            )
        else:
            out.append("\n\n" + gen_control(p, plan, u))

    # routing functions
    branching = [u for u in plan.units if u.kind == "control" and (p.node(u.id).node_type.branches or p.node(u.id).node_type.free_branches)]
    for u in branching:
        table: dict[str, list[str]] = {}
        for e in plan.succs(u.id):
            table.setdefault(e.label, []).append(e.target)
        items = ", ".join(f"{r(k)}: [{', '.join(r(t) for t in v)}]" for k, v in table.items())
        out.append(
            f"\n\ndef _after_{u.id}(state: rt.State) -> list[str]:\n"
            f"    return {{{items}}}.get(rt.branch_of(state, {r(u.id)}), [END])"
        )

    out += ["\n\n# ---- graph\n\n", "def build_graph(checkpointer=None):", "    g = StateGraph(rt.State)"]
    for u in plan.units:
        out.append(f"    g.add_node({r(u.id)}, {u.id})")
    out.append("")
    for u in plan.units:
        preds = [e for e in plan.preds(u.id) if e.label is None]
        if not plan.preds(u.id):
            out.append(f"    g.add_edge(START, {r(u.id)})")
        elif len(preds) > 1 and u.join == "all":
            out.append(f"    g.add_edge([{', '.join(r(e.source) for e in preds)}], {r(u.id)})  # wait for all")
        else:
            out += [f"    g.add_edge({r(e.source)}, {r(u.id)})" for e in preds]
    for u in branching:
        targets = sorted({e.target for e in plan.succs(u.id)})
        out.append(f"    g.add_conditional_edges({r(u.id)}, _after_{u.id}, [{', '.join(r(t) for t in targets)}{', ' if targets else ''}END])")
    for u in plan.units:
        if u not in branching and not plan.succs(u.id):
            out.append(f"    g.add_edge({r(u.id)}, END)")
    out += ["", "    return g.compile(checkpointer=checkpointer)", ""]
    return "\n".join(out)


def gen_main(p: Pipeline) -> str:
    return HEADER.format(name=p.name) + textwrap.dedent(f"""\
        import os
        import sys

        # The bundle ships the pipeline package and strand_runtime side by side under src/.
        sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

        import strand_runtime as rt  # noqa: E402
        from {p.name}.workflow import PIPELINE, SETTINGS, build_graph  # noqa: E402

        if __name__ == "__main__":
            rt.run(build_graph, pipeline=PIPELINE, settings=SETTINGS)
        """)


# ----------------------------------------------------------------------------- bundle


def gen_bundle(p: Pipeline, plan: Plan) -> dict[str, str]:
    deps = ["langgraph>=1.0", "langchain>=1.0", "databricks-langchain", "mlflow>=2.20"]
    kind = p.settings.checkpoint.kind
    if kind == "postgres":
        deps += ["langgraph-checkpoint-postgres", "psycopg[binary]"]
    elif kind == "sqlite":
        deps += ["langgraph-checkpoint-sqlite"]
    bundle = {
        "bundle": {"name": f"strand_{p.name}"},
        "include": ["resources/*.yml"],
        "targets": {"dev": {"mode": "development", "default": True}, "prod": {"mode": "production"}},
    }
    job = {
        "resources": {
            "jobs": {
                p.name: {
                    "name": f"strand · {p.name}",
                    "description": p.description or f"Generated by strand from pipeline '{p.name}'.",
                    "max_concurrent_runs": 10,
                    "parameters": [
                        {"name": "thread_id", "default": ""},
                        {"name": "resume", "default": ""},
                    ],
                    "tasks": [
                        {
                            "task_key": "run",
                            "environment_key": "default",
                            "spark_python_task": {
                                "python_file": f"../src/{p.name}/main.py",
                                "parameters": [
                                    "--run-id", "{{job.run_id}}",
                                    "--thread-id", "{{job.parameters.thread_id}}",
                                    "--resume", "{{job.parameters.resume}}",
                                ],
                            },
                        }
                    ],
                    "environments": [
                        {"environment_key": "default", "spec": {"environment_version": "2", "dependencies": deps}}
                    ],
                }
            }
        }
    }
    dump = lambda d: yaml.safe_dump(d, sort_keys=False, allow_unicode=True, width=120)  # noqa: E731
    return {"databricks.yml": dump(bundle), f"resources/{p.name}.job.yml": dump(job)}


def gen_readme(p: Pipeline, plan: Plan) -> str:
    lines = [f"# {p.name}", "", p.description or "", "", "Generated by strand. Steps, in order:", ""]
    for u in plan.units:
        if u.kind == "region":
            lines.append(f"- **{u.id}** (Spark): {' -> '.join(u.nodes)}")
            lines += [f"  - writes `{n}`: {why}" for n, why in u.materialize.items()]
        else:
            lines.append(f"- **{u.id}** ({p.node(u.id).node_type.label}, driver)")
    lines += [
        "", "## Deploy and run", "", "```bash", "databricks bundle deploy", f"databricks bundle run {p.name}", "```", "",
        "## Approve a paused run", "", "```bash",
        f"databricks bundle run {p.name} --params 'thread_id=<thread id>,resume={{\"approved\": true}}'", "```", "",
    ]
    return "\n".join(lines)


def compile_pipeline(p: Pipeline, plan: Plan) -> dict[str, str]:
    """All generated files, keyed by path relative to the output directory."""
    files = {
        "README.md": gen_readme(p, plan),
        f"src/{p.name}/__init__.py": "",
        f"src/{p.name}/transforms.py": gen_transforms(p, plan),
        f"src/{p.name}/workflow.py": gen_workflow(p, plan),
        f"src/{p.name}/main.py": gen_main(p),
        **gen_bundle(p, plan),
    }
    for f in sorted(RUNTIME_DIR.glob("*.py")):
        files[f"src/strand_runtime/{f.name}"] = f.read_text()
    return files


def write_files(files: dict[str, str], out_dir: Path) -> None:
    for rel, content in files.items():
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


# ----------------------------------------------------------------------------- preview


def gen_preview(p: Pipeline, node_id: str, limit: int) -> str:
    """A function that computes one dataflow node from limited sources."""
    needed: list[str] = []

    def walk(n: str) -> None:
        for e in p.data_inputs(n):
            walk(e.source)
        if n not in needed:
            needed.append(n)

    target = p.node(node_id)
    if target.kind != "dataflow":
        raise ValueError("Only dataflow nodes can be previewed.")
    if target.type == "sink":
        node_id = p.data_inputs(node_id)[0].source
    walk(node_id)
    body = [line for n in needed for line in node_expr(p, p.node(n), limit=limit)]
    return "def preview(spark):\n" + textwrap.indent("\n".join(body), "    ") + f"\n    return {node_id}.limit({limit})\n"
